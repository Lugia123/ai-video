def ref(r):
    if isinstance(r, str) and r.startswith('key:'):
        for p in (D / f'{r[4:]}.png', D / 'drafts/_pick' / f'{r[4:]}.png'):
            if p.exists(): return p
        sys.exit(f'还没有 {r[4:]}（把选中的草稿复制到 raw/drafts/_pick/{r[4:]}.png）')
    return r


def run(name, seed, final):
    w, h, refs, p = KEYS[name]
    out = D / (f'{name}.png' if final else f'drafts/{name}-s{seed}.png')
    if out.exists() and not final: return print('skip', out.name)
    out.parent.mkdir(parents=True, exist_ok=True)
    cmd = ['/usr/bin/python3', str(ROOT / 'tools/imggen/client.py'), 'edit', *map(str, map(ref, refs)), p, '--seed', str(seed), '-W', str(w), '-H', str(h), '-o', str(out)]
    if final: cmd.append('--final')
    r = subprocess.run(cmd, capture_output=True)
    print(('ok' if r.returncode == 0 else 'FAIL'), name, seed, flush=True)
    with open(D / 'calls.log', 'a') as f: f.write(f'{name} seed={seed} {"final" if final else "draft"} {w}x{h} code={r.returncode}\n')


REFINE = '保持图1的构图、人物、姿势、表情、物体的形状和位置、颜色、背景全部完全不变，一处都不要改动、不要增减任何东西。只把画面画得更干净精细：墨线更清晰锐利、粗细有变化，赛璐璐平涂的色块更干净，网点更整齐。不要文字。'


def refine(name):
    """定稿档：key/<名>.png（草稿档选中的图）→ key/final/<名>.png。同种子直接跑 40 步构图会变，所以改成「喂草稿、要求不变、只画干净」"""
    src = D.parent / 'key' / f'{name}.png'; out = D.parent / 'key' / 'final' / f'{name}.png'; out.parent.mkdir(exist_ok=True)
    if out.exists(): return print('skip', out.name)
    from PIL import Image
    w, h = Image.open(src).size
    r = subprocess.run(['/usr/bin/python3', str(ROOT / 'tools/imggen/client.py'), 'edit', str(src), REFINE, '--seed', '11', '-W', str(w), '-H', str(h), '-o', str(out), '--final'], capture_output=True)
    print(('ok' if r.returncode == 0 else 'FAIL'), 'refine', name, flush=True)
