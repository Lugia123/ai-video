#!/bin/zsh
# #1029 关盒子段 2D 俯视关键画（本地生图，不花钱）。用法：gen.sh <名字> <seed> [--final]   在仓库根目录跑
cd /Users/lugia/lugia_fc/ai_video
D=episodes/cast-cyber-girl/closeup/topdown
FACE=episodes/cast-cyber-girl/closeup/final/neutral.png
BODY=episodes/cast-cyber-girl/turnaround/master.png
STYLE="日本动画电影关键画风格，赛璐璐上色，干净的线条，不是Q版，不要文字，不要水印。保持图1女孩的脸、发型、发色、护目镜和粉色外套完全一致。"
ROOM="她在一个方形小房间底部，墙面和地面是光滑的深蓝灰色金属板（不是石头、不是砖），墙脚有粉色和薄荷绿的霓虹灯管，四周很暗，只有一束冷白的光从正上方打下来照亮她。"
typeset -A P
P[k1]="镜头在房间正上方很高的地方，垂直向下俯拍（鸟瞰视角）。图1的女孩站在房间正中，全身入画，在画面里非常小，只占画面高度的五分之一，她四周是大片空旷的地面，能看到房间的四面墙脚，她仰着头看向正上方的镜头。强烈的俯视透视：能看到她的头顶和仰起的脸，身体被透视压短，脚在最下面很小。$ROOM $STYLE"
P[k1t]="镜头在她头顶正上方、垂直向下俯拍（真正的 90 度俯视，像装在天花板正中的监控）。画面正中是图1女孩的头：她站着、把脸仰起来看着正上方的镜头，额头和护目镜在画面上方，下巴朝画面下方，能清楚看到她仰起的脸；肩膀在脸的两侧，两臂微微张开，身体被透视完全压在头的下面，只在下方露出一点鞋尖。她很小，只占画面高度的三成，四周是大片空旷的地面。地面是深蓝灰色的光滑金属地板，有细细的网格缝，一束冷白的顶光照着她，四周偏暗；画面里没有墙。$STYLE"
P[k1w]="保持图1的女孩、她的姿势、俯拍角度和画风完全不变，只把镜头拉远：女孩在画面正中缩小到只占画面高度的四分之一，她四周补出大片同样的深蓝灰色金属地板（有细的网格缝），顶光只照亮她周围一圈，越往外越暗。画面里没有墙、没有别的东西。"
P[k2]="镜头在正上方垂直向下俯拍。图1的女孩踮着脚，仰头看向镜头，右手用力向上伸向镜头，手指自然伸直、微微并拢（拇指加四根手指），像要够到镜头，手因为离镜头近而显得很大，手臂有强烈的透视缩短；她张着嘴在喊，表情焦急。半身入画，能看到头顶下方的肩膀和被透视压短的身体。$ROOM $STYLE"
P[k3]="镜头在正上方垂直向下俯拍的近景。图1的女孩仰着脸正对镜头，脸占满画面中央，眼睛睁大向上看着镜头，嘴闭着，表情害怕又倔强；能看到下方的肩膀和粉色外套领口因为俯视而变小。$ROOM $STYLE"
P[k4]="极近的大特写：图1女孩的一双眼睛横向占满整个画面，只看到眼睛、眉毛和鼻梁上端，她向上看着镜头，褐色的瞳孔里各映着一条横向的细细的白色亮线，眼眶微微湿润。背景很暗。$STYLE"
name=$1; seed=$2; shift 2
[[ -f $D/skip-$name ]] && exit 0      # 这个景别已经选好了：排着队的同名请求直接跳过，把显卡让出来
P[k2f]="保持图1的画面、构图、人物、表情、背景完全不变，只改一处：伸向镜头的那只手现在多了一根手指，把它改成正常的人手——一根拇指加四根手指，一共五根。"
P[k2c]="保持图1的画面、构图、人物、手、背景完全不变，只改一处：把女孩的嘴闭上，抿紧嘴唇，表情仍然焦急。"
refs=($FACE $BODY); [[ $name == k4 || $name == k3 ]] && refs=($FACE)
[[ $name == k2c ]] && refs=($D/k2-open.png)
[[ $name == k2f ]] && refs=($D/draft/k2-32.png)
[[ $name == k1w ]] && refs=($D/draft/k1t-72.png)
out=$D/draft/$name-$seed.png; [[ "$1" == "--final" ]] && out=$D/$name-$seed-final.png
perl -e 'alarm 900; exec @ARGV' /usr/bin/python3 tools/imggen/client.py edit $refs "${P[$name]}" -o $out --seed $seed -W 1664 -H 928 "$@" 2>&1 | tail -1
echo "$(date '+%F %T') $name seed=$seed $* -> $out" >> $D/calls.log
