#!/bin/bash
# 多角度五官批量生成（#936）：bash tools/face-bake/gen_yaw.sh <组> <状态|base> [seed]
# 每次调用追加一行到 episodes/cast-cyber-girl/closeup/yaw/calls.log（计数用；千问每次调用都花钱）
set -e
cd "$(dirname "$0")/../.."
set -a; . ~/.config/tts-keys; set +a
G=$1; S=$2; SEED=${3:-7}
D=episodes/cast-cyber-girl/closeup/yaw/$G
keep="其余所有部分（脸型、头部角度、头发、护目镜、衣服、背景、构图、线条和上色风格）完全保持不变。"
case $S in
  base)
    ref=$(python3 -c "import json;print(json.load(open('$D/ref.json'))['refYaw'])")
    dir=$(python3 -c "y=float('$ref'); print('正面朝向镜头（不转头）' if abs(y)<1 else ('头部朝画面左侧转约%d度' % round(abs(y))) if y>0 else ('头部朝画面右侧转约%d度' % round(abs(y))))")
    python3 tools/dt/qwen_edit.py --ref episodes/cast-cyber-girl/closeup/final/neutral.png --ref $D/ref-3d.png --seed $SEED --out $D/base.png --prompt "按第一张图的画风、人物的脸、发型、护目镜、服装和配色，把人物重画成第二张图的头部角度：${dir}，眼睛、鼻子、嘴的位置按第二张图。保持第一张图的日式动漫线稿平涂上色风格、白色背景、竖幅胸像构图，人物大小和位置与第一张相同。表情：双眼自然睁开看向镜头，嘴巴闭合、嘴角微微上扬。不要3D渲染质感，不要改变发型和服装。${EXTRA:-}" ;;
  closed) P="只修改眼睛：把两只眼睛都改成自然闭眼，上眼睑合拢成向下弯的睫毛线，看不到眼珠。眉毛、嘴巴和$keep" ;;
  half)   P="只修改眼睛：把两只眼睛都改成半闭（眼皮垂下盖住上半个眼珠，眼睛只睁开一半）。眉毛、嘴巴和$keep" ;;
  a) P="只修改嘴巴：把嘴改成张大的「啊」口型，嘴张开成椭圆，能看到上排牙齿和舌头。眼睛、眉毛和$keep" ;;
  i) P="只修改嘴巴：把嘴改成「衣」口型，嘴角向两边拉开，上下牙齿轻轻咬合露出一排牙齿，嘴张得很小。眼睛、眉毛和$keep" ;;
  u) P="只修改嘴巴：把嘴改成「乌」口型，嘴唇向前撅起收成一个小圆形，嘴很小。眼睛、眉毛和$keep" ;;
  e) P="只修改嘴巴：把嘴改成「诶」口型，嘴横向张开成扁椭圆，比「啊」小，能看到一点上排牙齿。眼睛、眉毛和$keep" ;;
  o) P="只修改嘴巴：把嘴改成竖着的圆形「哦」口型，嘴张开成竖椭圆，能看到口腔和舌头。眼睛、眉毛和$keep" ;;
  smile) P="只修改嘴巴：把嘴改成闭着嘴的微笑，嘴角明显向上扬起，嘴唇闭合。眼睛、眉毛和$keep" ;;
  surprised) P="只修改表情：惊讶——双眼睁大、黑眼珠变小一点，眉毛明显上扬，嘴张成一个小的竖椭圆形。头部角度、脸型、头发、护目镜、衣服、背景、构图、线条和上色风格完全保持不变。" ;;
  happy) P="只修改表情：开心大笑——双眼笑成向上弯的弧线（眯眼笑），嘴张开露出上排牙齿、嘴角高高上扬，脸颊微红。头部角度、脸型、头发、护目镜、衣服、背景、构图、线条和上色风格完全保持不变。" ;;
  sad) P="只修改表情：难过——眉头向中间上方皱起（八字眉），眼睛湿润、下眼睑有一点泪光，嘴角向下撇、嘴巴闭合。头部角度、脸型、头发、护目镜、衣服、背景、构图、线条和上色风格完全保持不变。" ;;
  angry) P="只修改表情：生气——眉毛向中间下方压低皱起，眼睛瞪着、眼神锐利，嘴巴紧闭、嘴角向下。头部角度、脸型、头发、护目镜、衣服、背景、构图、线条和上色风格完全保持不变。" ;;
  fear) P="只修改表情：害怕——眉毛上扬并向中间皱起，眼睛睁大、黑眼珠缩小，嘴巴微张、嘴角向两边拉紧，脸色稍微发白。头部角度、脸型、头发、护目镜、衣服、背景、构图、线条和上色风格完全保持不变。" ;;
  determined) P="只修改表情：坚定——眉毛平直略微压低，眼神专注有力直视镜头，嘴巴紧闭成一条直线、嘴角微微收紧。头部角度、脸型、头发、护目镜、衣服、背景、构图、线条和上色风格完全保持不变。" ;;
  plate) P="只修改头发和护目镜：去掉额前的刘海和头顶的护目镜，露出完整的额头、发际线和两条完整的眉毛（头发全部向后梳），脸、眼睛、嘴巴、头部角度、衣服、背景、构图、线条和上色风格完全保持不变。" ;;
  brows) P="只修改刘海：把额前刘海稍微向上撩起、变短一点，露出两条完整的眉毛。眼睛、嘴巴和$keep" ;;
  *) echo "未知状态 $S"; exit 1 ;;
esac
if [ "$S" != base ]; then
  out=$D/$S.png; [ "$S" = brows ] && out=$D/brows-base.png; [ -s "$out" ] && { echo "skip $out"; exit 0; }
  python3 tools/dt/qwen_edit.py --ref $D/base.png --seed $SEED --out $out --prompt "$P"
fi
echo "$(date '+%F %T') $G $S seed=$SEED" >> episodes/cast-cyber-girl/closeup/yaw/calls.log
